#!/usr/bin/env python3
"""
Generates the procedural sprite sheets of the vic sprite demo as C++ headers.
Run from the repo root:  python demo/sprite_sheets/gen_sheets.py
Each sheet is written as sprite_sheet_<name> (vic::sprite::sheet_info_type) with
the pixel data as byte array, least significant byte first.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def rgb565(r, g, b):
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return [v & 0xFF, v >> 8]


def argb8888(r, g, b, a):
    # B G R A, so that the little endian uint32 is ARGB
    return [b, g, r, a]


class Sheet:
    def __init__(self, name, frame_w, frame_h, frames, fmt, bg, comment):
        self.name, self.fw, self.fh, self.frames = name, frame_w, frame_h, frames
        self.fmt, self.bg, self.comment = fmt, bg, comment
        self.w, self.h = frame_w * frames, frame_h
        # pixels as (r, g, b, a), a == 0 is transparent
        self.px = [[(0, 0, 0, 0) for _ in range(self.w)] for _ in range(self.h)]

    def set(self, frame, x, y, r, g, b, a=255):
        if 0 <= x < self.fw and 0 <= y < self.fh:
            self.px[y][frame * self.fw + x] = (max(0, min(255, int(r))), max(0, min(255, int(g))),
                                               max(0, min(255, int(b))), max(0, min(255, int(a))))

    def get(self, frame, x, y):
        if 0 <= x < self.fw and 0 <= y < self.fh:
            return self.px[y][frame * self.fw + x]
        return (0, 0, 0, 0)

    def write(self):
        data = []
        for row in self.px:
            for (r, g, b, a) in row:
                if self.fmt == 'RGB565':
                    # transparent pixels are black (the sheet background color)
                    data += rgb565(r, g, b) if a else [0, 0]
                else:
                    data += argb8888(r, g, b, a) if a else [0, 0, 0, 0]
        lines = []
        for i in range(0, len(data), 16):
            lines.append('  ' + ', '.join('0x%02X' % v for v in data[i:i + 16]) + ',')
        fmt = {'RGB565': 'vic::color::format_RGB565', 'ARGB8888': 'vic::color::format_ARGB8888'}[self.fmt]
        bg = {'RGB565': 'vic::color::black', 'ARGB8888': 'vic::color::none'}[self.fmt]
        text = (
            '// %s sprite sheet\n'
            '// %s\n'
            '// %u frames of %u x %u pixel, %s, generated by gen_sheets.py - do not edit\n'
            '\n'
            '#ifndef _VIC_DEMO_SPRITE_SHEET_%s_H_\n'
            '#define _VIC_DEMO_SPRITE_SHEET_%s_H_\n'
            '\n'
            '#include "sprite.h"\n'
            '\n'
            'static const std::uint8_t sprite_sheet_%s_data[%u] = {\n'
            '%s\n'
            '};\n'
            '\n'
            'static const vic::sprite::sheet_info_type sprite_sheet_%s = {\n'
            '  %u,%s// sheet width\n'
            '  %u,%s// sheet height\n'
            '  %u,%s// sprite width\n'
            '  %u,%s// sprite height\n'
            '  %s,%s// sprite background color (transparent)\n'
            '  %s,%s// data format\n'
            '  sprite_sheet_%s_data\n'
            '};\n'
            '\n'
            '#endif  // _VIC_DEMO_SPRITE_SHEET_%s_H_\n'
        ) % (self.name.capitalize(), self.comment, self.frames, self.fw, self.fh, self.fmt,
             self.name.upper(), self.name.upper(), self.name, len(data), '\n'.join(lines), self.name,
             self.w, ' ' * 25, self.h, ' ' * 25, self.fw, ' ' * 25, self.fh, ' ' * 25,
             bg, ' ' * (28 - len(bg)), fmt, ' ' * (28 - len(fmt)), self.name, self.name.upper())
        path = os.path.join(HERE, self.name + '.h')
        with open(path, 'w', newline='\n') as f:
            f.write(text)
        print('%s: %u x %u, %u bytes' % (path, self.w, self.h, len(data)))


def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


# ---------------------------------------------------------------------------
# coin: spinning gold coin, 8 frames 16 x 16, RGB565
def gen_coin():
    s = Sheet('coin', 16, 16, 8, 'RGB565', 'black', 'Spinning gold coin')
    gold, dark, light = (240, 190, 40), (170, 120, 20), (255, 240, 170)
    for f in range(8):
        ang = f * math.pi / 8.0
        rx = 7.0 * abs(math.cos(ang))
        ry = 7.0
        cx, cy = 7.5, 7.5
        for y in range(16):
            for x in range(16):
                dx, dy = (x + 0.5 - cx), (y + 0.5 - cy)
                if rx < 1.2:
                    # edge on: a thin bar
                    if abs(dx) < 1.0 and abs(dy) <= ry:
                        s.set(f, x, y, *dark)
                    continue
                d = (dx / rx) ** 2 + (dy / ry) ** 2
                if d <= 1.0:
                    if d > 0.72:
                        c = dark
                    elif (dx + dy) < -3.5 * (rx / 7.0):
                        c = light
                    else:
                        c = gold
                    # the "C" emboss in the middle for the face on view
                    if rx > 4.5:
                        r2 = (dx / (rx * 0.5)) ** 2 + (dy / 3.5) ** 2
                        if 0.55 < r2 < 1.0 and dx < 1.5:
                            c = dark
                    s.set(f, x, y, *c)
    s.write()


# ghost: floating ghost with transparent body, 4 frames 24 x 24, ARGB8888
def gen_ghost():
    s = Sheet('ghost', 24, 24, 4, 'ARGB8888', 'none', 'Floating ghost, the body is semi transparent')
    body, eye, blush = (230, 240, 255), (40, 40, 90), (255, 150, 170)
    for f in range(4):
        phase = f * math.pi / 2.0
        for y in range(24):
            for x in range(24):
                dx = x + 0.5 - 12.0
                inside = False
                if y < 10:
                    inside = (dx ** 2 + (y + 0.5 - 10.0) ** 2) <= 81.0
                else:
                    # wavy skirt
                    bottom = 20.0 + 2.0 * math.sin(x * 0.9 + phase)
                    inside = abs(dx) <= 9.0 and y + 0.5 <= bottom
                if inside:
                    edge = abs(dx) > 7.5 or y < 3
                    c = shade(body, 0.8) if edge else body
                    a = 200 if edge else 165
                    s.set(f, x, y, c[0], c[1], c[2], a)
        # eyes (opaque) and blush
        ey = 9 + (1 if f in (1, 2) else 0)
        for ex in (8, 15):
            for yy in range(ey - 1, ey + 2):
                for xx in range(ex - 1, ex + 2):
                    s.set(f, xx, yy, *eye)
            s.set(f, ex - 1, ey - 1, 120, 120, 170)
        for bx in (6, 17):
            s.set(f, bx, 13, blush[0], blush[1], blush[2], 160)
            s.set(f, bx + (1 if bx < 12 else -1), 13, blush[0], blush[1], blush[2], 160)
    s.write()


# ship: small space ship, 3 frames (level, banking up, banking down) 24 x 16, RGB565
def gen_ship():
    s = Sheet('ship', 24, 16, 3, 'RGB565', 'black', 'Space ship: frame 0 level, 1 banking up, 2 banking down')
    hull, hull_dark, glass, wing, flame, flame2 = (190, 195, 210), (110, 115, 130), (80, 220, 255), (200, 60, 60), (255, 200, 40), (255, 120, 20)
    for f in range(3):
        bank = {0: 0, 1: -1, 2: 1}[f]
        for y in range(16):
            for x in range(24):
                dx, dy = x + 0.5 - 13.0, y + 0.5 - 8.0
                # hull: ellipse, pointed to the right
                if (dx / 9.0) ** 2 + (dy / 3.2) ** 2 <= 1.0:
                    c = hull_dark if dy > 1.5 else hull
                    s.set(f, x, y, *c)
                # cockpit
                if (dx - 3.0) ** 2 / 6.0 + (dy + 0.8) ** 2 / 1.6 <= 1.0 and dy < 0.8:
                    s.set(f, x, y, *glass)
        # wings
        for x in range(6, 15):
            w = (x - 6) // 3
            yu = 8 - 4 + w + bank
            yd = 8 + 3 - w + bank
            for yy in (yu, yu + 1):
                s.set(f, x, yy, *wing)
            for yy in (yd, yd + 1):
                s.set(f, x, yy, *wing)
        # engine flame
        for i, x in enumerate(range(1, 5)):
            c = flame if (i + f) % 2 == 0 else flame2
            h = 1 if x < 3 else 2
            for yy in range(8 - h, 8 + h):
                s.set(f, x, yy, *c)
    s.write()


# star: sparkle / burst animation, 6 frames 32 x 32, ARGB8888
def gen_star():
    s = Sheet('star', 32, 32, 6, 'ARGB8888', 'none', 'Burst / sparkle animation, plays once')
    for f in range(6):
        t = f / 5.0
        cx = cy = 15.5
        # center flash
        fr = 6.0 * (1.0 - t) + 1.0
        for y in range(32):
            for x in range(32):
                d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
                if d <= fr:
                    k = d / fr
                    a = int(255 * (1.0 - t) * (1.0 - k * 0.6))
                    s.set(f, x, y, 255, 255 - int(80 * k), 200 - int(200 * k), a)
        # particles
        for p in range(12):
            ang = p * math.pi / 6.0 + t * 0.6
            r = 3.0 + t * 12.0
            px, py = cx + r * math.cos(ang), cy + r * math.sin(ang)
            pr = 2.2 - t * 1.2
            for y in range(32):
                for x in range(32):
                    d = math.hypot(x + 0.5 - px, y + 0.5 - py)
                    if d <= pr:
                        a = int(255 * (1.0 - t * 0.8))
                        col = (255, 230 - int(150 * t), 60) if p % 2 else (255, 120 + int(100 * (1 - t)), 40)
                        old = s.get(f, x, y)
                        if old[3] < a:
                            s.set(f, x, y, col[0], col[1], col[2], a)
    s.write()


if __name__ == '__main__':
    gen_coin()
    gen_ghost()
    gen_ship()
    gen_star()
