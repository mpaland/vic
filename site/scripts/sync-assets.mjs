// Copies repo assets into the site before dev/build, so nothing is duplicated in git:
//   doc/demo_*.{gif,png}        -> public/media/
//   src/font/ttf/*              -> src/assets/fonts/   (OFL fonts, bundled by Vite)
//   src/font/ttf/*-OFL.txt      -> public/fonts/       (their licences)
//   CHANGELOG.md                -> src/content/docs/changelog.md
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(site, '..');

function copyMatching(srcDir, dstDir, re) {
	mkdirSync(dstDir, { recursive: true });
	let n = 0;
	for (const f of readdirSync(srcDir)) {
		if (re.test(f)) {
			copyFileSync(join(srcDir, f), join(dstDir, f));
			n++;
		}
	}
	return n;
}

const media = copyMatching(join(repo, 'doc'), join(site, 'public', 'media'), /^demo_.*\.(gif|png)$/);
const fonts = copyMatching(join(repo, 'src', 'font', 'ttf'), join(site, 'src', 'assets', 'fonts'), /\.ttf$/);
copyMatching(join(repo, 'src', 'font', 'ttf'), join(site, 'public', 'fonts'), /-OFL\.txt$/);   // font licences, published

// changelog: drop the top level title, demote nothing else, add frontmatter
let log = readFileSync(join(repo, 'CHANGELOG.md'), 'utf8').replace(/\r\n/g, '\n');
log = log.replace(/^# .*\n+/, '');
writeFileSync(
	join(site, 'src', 'content', 'docs', 'changelog.md'),
	'---\ntitle: Changelog\ndescription: Release history of vic, generated from CHANGELOG.md\neditUrl: false\n---\n\n' +
		'<!-- generated by scripts/sync-assets.mjs from ../CHANGELOG.md, do not edit -->\n\n' +
		log,
);

console.log(`sync-assets: ${media} media, ${fonts} font files, changelog`);
